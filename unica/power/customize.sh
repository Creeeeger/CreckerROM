# Run after all platform/device patches and ROM mods have copied their files.
POWER_POLICY_ARGS=()
if [ "${DEBUG:-false}" = "true" ]; then
    POWER_POLICY_ARGS+=(--debug)
fi
python3 "$SRC_DIR/unica/power/configure.py" "$WORK_DIR" "${POWER_POLICY_ARGS[@]}" || return 1

# Set persistent properties after /data properties have loaded, so flashing over
# a debug build cannot retain the previous verbose masks or RAM Plus size.
POWER_POLICY_STAGE="$(mktemp -d)" || return 1
mkdir -p "$POWER_POLICY_STAGE/system/system/etc/init"
POWER_POLICY_RC="$POWER_POLICY_STAGE/system/system/etc/init/init.power-policy-manager.rc"
{
    echo '# Generated by Power Policy Manager'
    for POWER_POLICY_EVENT in 'property:ro.persistent_properties.ready=true' 'property:sys.boot_completed=1'; do
        echo "on $POWER_POLICY_EVENT"
        if [ "${DEBUG:-false}" = "true" ]; then
            echo '    setprop persist.log.level 0xFFFFFFFF'
            echo '    setprop persist.log.semlevel 0xFFFFFFFF'
            echo '    setprop persist.log.tag V'
        else
            echo '    setprop persist.log.level 0x0'
            echo '    setprop persist.log.semlevel 0x0'
            echo '    setprop persist.log.tag W'
        fi
        echo '    setprop persist.sys.zram.ram_expand_size 0'
        echo ''
    done
} > "$POWER_POLICY_RC"
if ! ADD_TO_WORK_DIR "$POWER_POLICY_STAGE" system system/etc/init/init.power-policy-manager.rc 0 0 644 u:object_r:system_file:s0; then
    rm -rf "$POWER_POLICY_STAGE"
    return 1
fi
rm -rf "$POWER_POLICY_STAGE"
unset POWER_POLICY_ARGS POWER_POLICY_STAGE POWER_POLICY_RC POWER_POLICY_EVENT
